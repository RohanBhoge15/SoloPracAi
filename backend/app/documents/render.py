# ── shell ──────────────────────────────────────────────────────────


def watermark(text: str) -> str:
    return f'<div class="watermark">{escape(text)}</div>'


def rupees(amount: float) -> str:
    """Indian digit grouping: 1,23,456.00 not 123,456.00."""
    try:
        value = float(amount)
    except (TypeError, ValueError):
        return "0.00"
    negative = value < 0
    value = abs(value)
    whole = int(value)
    paise = int(round((value - whole) * 100))
    if paise == 100:
        whole += 1
        paise = 0

    s = str(whole)
    if len(s) > 3:
        head, tail = s[:-3], s[-3:]
        parts = []
        while len(head) > 2:
            parts.insert(0, head[-2:])
            head = head[:-2]
        if head:
            parts.insert(0, head)
        s = ",".join(parts + [tail])
    return f"{'-' if negative else ''}{s}.{paise:02d}"


def fmt_date(value) -> str:
    if value is None:
        return "—"
    if isinstance(value, datetime):
        return value.strftime("%d %b %Y")
    try:
        return datetime.fromisoformat(str(value)).strftime("%d %b %Y")
    except (ValueError, TypeError):
        return str(value)


def patient_block(patient: dict) -> str:
    # Sex is only labelled when we have a value for it.
    #
    # This used to be a hardcoded f"{age} / —", which printed "23 / —" on
    # every prescription: there is no `sex` column on the patient row and no
    # field anywhere that collects one, so the dash was not a missing value,
    # it was a literal in the format string. An always-empty field on a
    # clinical document reads as "the doctor did not record this", which is
    # worse than not offering it.
    #
    # Sex is kept rather than deleted because it is clinically meaningful on a
    # prescription. If it is ever collected, the label appears on its own
    # instead of the document quietly losing the field.
    age = patient.get("age")
    sex = patient.get("sex")
    cells = [
        ("Patient", patient.get("display_name") or "—"),
        ("Age / Sex", f"{age} / {sex}") if sex else ("Age", age or "—"),
        ("Phone", patient.get("phone") or "—"),
        ("Patient ID", (patient.get("id") or "")[:8].upper() or "—"),
    ]
    if patient.get("abha_number"):
        cells.append(("ABHA", patient["abha_number"]))
    rendered = "".join(
        f'<div class="patient-cell">'
        f'<div class="patient-label">{escape(label)}</div>'
        f'<div class="patient-value">{escape(str(value))}</div>'
        f"</div>"
        for label, value in cells
    )
    return f'<div class="patient">{rendered}</div>'


def doctor_block(doctor: dict) -> str:
    account = doctor.get("account") or {}
    name = account.get("display_name") or doctor.get("display_name") or "—"
    meta = []
    if doctor.get("specialty"):
        meta.append(doctor["specialty"])
    if doctor.get("clinic_name"):
        meta.append(doctor["clinic_name"])
    if doctor.get("nmc_number"):
        meta.append(f"NMC Reg. {doctor['nmc_number']}")
    credentials = []
    if doctor.get("registration_state"):
        credentials.append(f"<strong>{escape(doctor['registration_state'])}</strong>")
    if doctor.get("email"):
        credentials.append(escape(doctor["email"]))
    if doctor.get("phone"):
        credentials.append(escape(doctor["phone"]))

    # The separator is a real middot character, not the &middot; entity.
    # WeasyPrint resolves entities fine, but mixing them with escaped
    # text is how literal "&middot;" ends up printed on a legal document.
    meta_text = " · ".join(meta)
    return (
        '<div class="masthead">'
        f'<div><div class="clinic-name">'
        f'{escape(doctor.get("clinic_name") or "SoloPrac Clinic")}</div>'
        f'<div class="doctor-name">{escape(name)}</div>'
        f'<div class="doctor-meta">{escape(meta_text)}</div></div>'
        f'<div class="credentials">{"".join(credentials)}</div>'
        "</div>"
    )


def signature_block(
    doctor: dict,
    role: str = "Consultant",
    issued_at: Optional[datetime] = None,
) -> str:
    """Signature and date line.

    The date is printed, not left blank. These are legal documents: an
    undated prescription is no evidence of when the advice was given, and a
    patient holding one later cannot reconstruct it. It was previously a
    bare "Date" label over an empty rule, which read like space left for a
    handwritten date but was indistinguishable from a bug once the document
    was issued digitally.
    """
    account = doctor.get("account") or {}
    name = account.get("display_name") or doctor.get("display_name") or "—"
    qual = doctor.get("specialty") or role
    reg = ""
    if doctor.get("nmc_number"):
        reg = f'<div class="signature-role">Reg. {escape(doctor["nmc_number"])}</div>'

    date_label = (
        f'<div class="signature-name">'
        f'{escape(fmt_date(issued_at or datetime.now()))}</div>'
    )

    return (
        '<div class="signature">'
        '<div class="signature-block">'
        '<div class="signature-line">'
        f'<div class="signature-name">{escape(name)}</div>'
        f'<div class="signature-role">{escape(qual)}</div>'
        f"{reg}</div></div>"
        '<div class="signature-block">'
        '<div class="signature-line">'
        f"{date_label}"
        '<div class="signature-role">Date of issue</div>'
        "</div></div>"
        "</div>"
    )


def shell(
    *,
    kind_title: str,
    reference: str,
    doctor: dict,
    patient: dict,
    watermark_text: str,
    body: str,
    provenance: str = "",
    issued_at: Optional[datetime] = None,
) -> str:
    """Wrap document content in the shared shell.

    `issued_at` is threaded through to the signature block so every
    document carries a date. It is passed in rather than read from the
    clock here so the printed date is the instant the record was written,
    not whenever the PDF happened to be rendered.
    """
    prov = ""
    if provenance:
        prov = f'<div class="provenance">{provenance}</div>'
    return f"""<!DOCTYPE html>
<html lang="en"><head><meta charset="utf-8">
<title>{escape(kind_title)}</title>
<style>{BASE_CSS}</style>
</head><body>
{watermark(watermark_text)}
<div class="page">
  {doctor_block(doctor)}
  <h1 class="doc-kind">{escape(kind_title)}</h1>
  <div class="doc-ref">{escape(reference)}</div>
  {patient_block(patient)}
  {body}
  {signature_block(doctor, issued_at=issued_at)}
  {prov}
</div>
</body></html>"""
